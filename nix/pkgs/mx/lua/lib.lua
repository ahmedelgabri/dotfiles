-- Loads and writes mx session definitions. Shared by the tmux backend, which
-- runs it with LuaJIT, and the Rex backend, which runs it inside `rex do`.
-- Both are Lua 5.1, so this file must stay within Lua 5.1.

local M = {}

local function quote(s)
	return "'" .. s:gsub("'", "'\\''") .. "'"
end

-- Rex removed os.execute from its Lua, and rex.exec runs no shell, so each
-- runtime gets its own way to run `sh -c`. The argument travels as $1 so it
-- never needs quoting inside the script.
local function sh_ok(script, arg)
	if rex ~= nil then
		local result = rex.exec { 'sh', '-c', script, 'sh', arg }
		return result ~= nil and result.ok
	end
	return os.execute('set -- ' .. quote(arg) .. '; ' .. script) == 0
end

-- Definitions see these as the global `mx`.
local helpers = {
	has = function(cmd)
		return sh_ok('command -v "$1" >/dev/null 2>&1', cmd)
	end,
	isdir = function(path)
		return path ~= nil and path ~= '' and sh_ok('test -d "$1"', path)
	end,
}

local function resolve(cwd, root)
	if cwd == nil then
		return root
	end
	if cwd:sub(1, 1) == '/' then
		return cwd
	end
	return root .. '/' .. cwd
end

local function normalize(node, root, where)
	if type(node) ~= 'table' then
		error(where .. ': must be a table', 0)
	end
	if node.split == nil then
		if node[1] ~= nil then
			error(where .. ': a pane cannot hold children; add split', 0)
		end
		return {
			cwd = resolve(node.cwd, root),
			command = node.command,
			focus = node.focus == true,
		}
	end
	if node.split ~= 'horizontal' and node.split ~= 'vertical' then
		error(where .. ": split must be 'horizontal' or 'vertical'", 0)
	end
	local ratio = node.ratio or 0.5
	if type(ratio) ~= 'number' or ratio <= 0 or ratio >= 1 then
		error(where .. ': ratio must be between 0 and 1', 0)
	end
	if node[1] == nil or node[2] == nil or node[3] ~= nil then
		error(where .. ': a split needs exactly two children', 0)
	end
	return {
		split = node.split,
		ratio = ratio,
		normalize(node[1], root, where .. '[1]'),
		normalize(node[2], root, where .. '[2]'),
	}
end

-- Returns { root = <abs path>, windows = { { label =, layout = } } } with
-- every pane's cwd made absolute. A definition with no windows gets one
-- plain pane at root.
function M.load(path, root)
	local chunk, err = loadfile(path)
	if chunk == nil then
		error(err, 0)
	end
	setfenv(chunk, setmetatable({ mx = helpers }, { __index = _G }))
	local ok, spec = pcall(chunk)
	if not ok then
		error(path .. ': ' .. tostring(spec), 0)
	end
	if type(spec) ~= 'table' then
		error(path .. ': must return a table', 0)
	end
	root = spec.root or root
	local windows = {}
	for i, w in ipairs(spec.windows or {}) do
		local where = path .. ': windows[' .. i .. ']'
		if type(w) ~= 'table' then
			error(where .. ': must be a table', 0)
		end
		table.insert(windows, {
			label = w.label,
			layout = normalize(w.layout or {}, root, where .. '.layout'),
		})
	end
	return { root = root, windows = windows }
end

function M.plain(root)
	return { root = root, windows = {} }
end

-- Fills in the one pane every session starts with.
function M.windows(def)
	if #def.windows > 0 then
		return def.windows
	end
	return { { layout = { cwd = def.root, focus = false } } }
end

-- Panes in tree order, which is also the order both backends create them in.
function M.panes(node, out)
	out = out or {}
	if node.split then
		M.panes(node[1], out)
		M.panes(node[2], out)
	else
		table.insert(out, node)
	end
	return out
end

-- Export ---------------------------------------------------------------------

-- Quotes the way stylua's AutoPreferSingle does, so an exported file passes
-- `stylua --check` unchanged.
local function q(s)
	local mark = "'"
	if s:find("'", 1, true) and not s:find('"', 1, true) then
		mark = '"'
	end
	return mark
		.. s:gsub('[%c\\' .. mark .. ']', function(c)
			if c == '\n' then
				return '\\n'
			elseif c == '\t' then
				return '\\t'
			elseif c == '\\' or c == mark then
				return '\\' .. c
			end
			return string.format('\\%03d', c:byte())
		end)
		.. mark
end

local function home_expr(path, home)
	if path == home then
		return "os.getenv 'HOME'"
	end
	if path:sub(1, #home + 1) == home .. '/' then
		return "os.getenv 'HOME' .. " .. q(path:sub(#home + 1))
	end
	return q(path)
end

local function cwd_expr(cwd, root, home)
	if cwd == nil or cwd == root then
		return nil
	end
	if cwd:sub(1, #root + 1) == root .. '/' then
		return q(cwd:sub(#root + 2))
	end
	return home_expr(cwd, home)
end

-- Enough digits that rebuilding at the same size gives the same cells.
local function ratio_expr(ratio)
	local s = string.format('%.4f', ratio):gsub('0+$', '')
	return s
end

function M.exported(session)
	return 'Generated by mx --export from session ' .. q(session)
end

function M.migrated(path)
	return 'Converted by mx --migrate from ' .. q(path)
end

local function pad(n)
	return string.rep('\t', n)
end

-- Every table is written expanded, one field per line, which is also how
-- stylua keeps them.
local function emit(node, root, home, depth, prefix, out)
	table.insert(out, pad(depth) .. prefix .. '{')
	local inner = pad(depth + 1)
	if node.split then
		table.insert(out, inner .. 'split = ' .. q(node.split) .. ',')
		table.insert(out, inner .. 'ratio = ' .. ratio_expr(node.ratio) .. ',')
		emit(node[1], root, home, depth + 1, '', out)
		emit(node[2], root, home, depth + 1, '', out)
	else
		if node.process ~= nil then
			local process = node.process:gsub('%c', ' ')
			table.insert(
				out,
				inner .. '-- running ' .. process .. ' (command not recorded)'
			)
		end
		local cwd = cwd_expr(node.cwd, root, home)
		if cwd ~= nil then
			table.insert(out, inner .. 'cwd = ' .. cwd .. ',')
		end
		if node.command ~= nil then
			table.insert(out, inner .. 'command = ' .. q(node.command) .. ',')
		end
		if node.focus then
			table.insert(out, inner .. 'focus = true,')
		end
	end
	if out[#out] == pad(depth) .. prefix .. '{' then
		out[#out] = out[#out] .. '},'
	else
		table.insert(out, pad(depth) .. '},')
	end
end

-- windows: { { label =, layout = <normalized tree>, note = <comment> } }.
-- A pane may carry `process` (a program whose command was not recorded),
-- which becomes a comment. `origin` says where the file came from.
function M.serialize(origin, root, windows, home)
	local out = {
		'-- ' .. origin .. '.',
		'-- Windows from shared.lua are omitted; mx adds them to new sessions.',
		'-- Recorded commands are replayed. Review them for secrets before saving.',
		'-- Programs without a recorded command stay as comments.',
		'',
		'return {',
		'\troot = ' .. home_expr(root, home) .. ',',
		'\twindows = {',
	}
	for _, w in ipairs(windows) do
		table.insert(out, '\t\t{')
		if w.label ~= nil then
			table.insert(out, '\t\t\tlabel = ' .. q(w.label) .. ',')
		end
		if w.note ~= nil then
			table.insert(out, '\t\t\t-- ' .. w.note)
		end
		emit(w.layout, root, home, 3, 'layout = ', out)
		table.insert(out, '\t\t},')
	end
	table.insert(out, '\t},')
	table.insert(out, '}')
	return table.concat(out, '\n') .. '\n'
end

return M
